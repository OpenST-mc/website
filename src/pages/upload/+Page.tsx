import { useMemo, useState, type ChangeEvent } from 'react';
import JSZip from 'jszip';
import { marked } from 'marked';
import DOMPurify from 'dompurify';
import { TAG_CONFIG } from '../../lib/config';
import { previewFileName } from '../../lib/packer';
import { submitIssue } from '../../lib/api';
import { signIn, signOut } from '../../lib/auth';
import { useSession } from '../../hooks/useSession';
import './upload.css';

const WORKER_URL = 'https://api.openstmc.com';

const DEFAULT_DESC = `### 🚀 机器概览（示例）\n- **核心功能**: \n- **适用版本**: Java 1.20.x\n\n### 📖 使用说明\n1. 在非原版特性端使用时，请先测试机器能否正常工作后再进行实装\n2. 说明2\n\n> 提示：本机器支持横向堆叠。`;

interface ProcessedCategory {
  mainCat: string;
  nested: Array<{ subCat: string; tags: string[] }>;
  flattened: string[];
}

export default function Page() {
  const { user, status } = useSession();
  const [step, setStep] = useState(1);
  const [name, setName] = useState('');
  const [author, setAuthor] = useState('');
  const [contact, setContact] = useState('');
  const [desc, setDesc] = useState(DEFAULT_DESC);
  const [tags, setTags] = useState<string[]>([]);
  const [previewFile, setPreviewFile] = useState<File | null>(null);
  const [litematicFile, setLitematicFile] = useState<File | null>(null);
  const [githubIssueUrl, setGithubIssueUrl] = useState('');

  const previewHtml = useMemo(() => {
    if (!desc) return '<span class="text-gray-600 italic">在此输入简介...</span>';
    try {
      return DOMPurify.sanitize(String(marked.parse(desc)));
    } catch {
      return desc;
    }
  }, [desc]);

  const processedConfig = useMemo<ProcessedCategory[]>(() => {
    return Object.entries(TAG_CONFIG).map(([mainCat, subConfig]) => {
      if (Array.isArray(subConfig)) return { mainCat, nested: [], flattened: subConfig };
      const nested: ProcessedCategory['nested'] = [];
      const flattened: string[] = [];
      Object.entries(subConfig).forEach(([subCat, catTags]) => {
        if (catTags && catTags.length > 0) nested.push({ subCat, tags: catTags });
        else flattened.push(subCat);
      });
      return { mainCat, nested, flattened };
    });
  }, []);

  const isReady = Boolean(name && previewFile && litematicFile);

  const toggleTag = (tag: string, parentKey: string | null = null) => {
    setTags((prev) => {
      if (prev.includes(tag)) {
        const next = prev.filter((t) => t !== tag);
        for (const mainConfig of Object.values(TAG_CONFIG)) {
          if (mainConfig && !Array.isArray(mainConfig) && Array.isArray(mainConfig[tag])) {
            return next.filter((t) => !mainConfig[tag]?.includes(t));
          }
        }
        return next;
      }
      const next = [...prev, tag];
      if (parentKey && !next.includes(parentKey)) next.push(parentKey);
      return next;
    });
  };

  const handleUpload = async () => {
    if (!user || step === 2 || !previewFile || !litematicFile) return;
    setStep(2);
    try {
      const zip = new JSZip();
      const safeFolderName = name.replace(/[#\\/:*?"<>|]/g, '_');
      const folder = zip.folder(safeFolderName);
      if (!folder) throw new Error('zip folder failed');
      const previewName = previewFileName(previewFile.name);
      const now = new Date();
      const originalFileName = litematicFile.name;
      const infoJson = {
        id: `sub-${now.getTime()}`,
        name,
        author: author || '匿名',
        tags,
        description: desc,
        folder: safeFolderName,
        preview: previewName,
        filename: originalFileName,
        submitDate: now.toISOString(),
      };

      folder.file('info.json', JSON.stringify(infoJson, null, 4));
      folder.file(previewName, previewFile);
      folder.file(originalFileName, litematicFile);

      const zipBlob = await zip.generateAsync({ type: 'blob' });

      const fd = new FormData();
      fd.append('name', name);
      fd.append('zip', zipBlob, `submission_${safeFolderName}.zip`);
      fd.append('preview', previewFile);

      const workerRes = await fetch(`${WORKER_URL}/api/archive-upload`, { method: 'POST', body: fd });
      if (!workerRes.ok) throw new Error('Worker 文件中继失败');
      const { downloadUrl, filePath } = (await workerRes.json()) as { downloadUrl?: string; filePath?: string };
      const domesticDownloadUrl = downloadUrl || `${WORKER_URL}/dl/${filePath}`;

      const issueBody = `## 🚀 机器投递: ${name}

> [!IMPORTANT]
> **存档审核直连下载 (国内加速)**: [📥 点击下载投稿全量包](${domesticDownloadUrl})

### 📋 自动生成配置 (info.json)
\`\`\`json
${JSON.stringify(infoJson, null, 4)}
\`\`\`

---
**📝 投稿详情**
- **作者**: ${author}
- **联系方式**: ${contact || '未提供'}
- **简介**: 
${desc}

_Generated by OpenST Portal 4.0_`;

      const issueRes = await submitIssue({ title: `[档案馆] ${name} @${author}`, labels: ['档案馆'], body: issueBody });
      if (!issueRes.ok) throw new Error('GitHub 提交失败');
      const ghData = (issueRes.json ?? {}) as { html_url?: string };
      setGithubIssueUrl(ghData.html_url ?? '');
      setStep(3);
    } catch (e) {
      console.error(e);
      alert('投递失败: ' + (e as Error).message);
      setStep(1);
    }
  };

  const loggedIn = status === 'authenticated' && Boolean(user);

  return (
    <div className="bg-[#121212] text-white antialiased font-sans">
      <div className="min-h-screen bg-[#121212] py-12 px-4 flex justify-center items-start font-sans text-gray-200">
        <div className="bg-[#1a1a1a] w-full max-w-4xl rounded-[2rem] border border-white/10 shadow-2xl flex flex-col overflow-hidden">
          <div className="p-8 border-b border-white/5 flex justify-between items-center bg-white/[0.02]">
            <div>
              <h2 className="text-2xl font-bold text-white tracking-tight">机器存档投递</h2>
              <p className="text-[#40B5AD] text-[10px] font-bold uppercase tracking-[0.2em] mt-1">Submission Portal</p>
            </div>
            <div className="flex items-center gap-4">
              {loggedIn ? (
                <button
                  type="button"
                  onClick={() => void signOut('/upload')}
                  className="text-xs text-red-500/60 hover:text-red-500 underline uppercase tracking-widest"
                >
                  注销登录
                </button>
              ) : null}
              <a
                href="../archive/index.html"
                className="text-gray-500 hover:text-white transition-all text-sm border border-white/10 px-4 py-2 rounded-full"
              >
                返回首页
              </a>
            </div>
          </div>

          <div className="p-8">
            {status === 'loading' ? (
              <div className="py-24 text-center text-gray-500">正在连接存档系统...</div>
            ) : null}

            {!loggedIn && status !== 'loading' && step === 1 ? (
              <div className="py-20 text-center space-y-8">
                <div className="w-20 h-20 bg-[#40B5AD]/10 rounded-3xl flex items-center justify-center mx-auto mb-4 border border-[#40B5AD]/20 rotate-3">
                  <span className="text-4xl">🔑</span>
                </div>
                <div className="max-w-xs mx-auto space-y-3">
                  <h3 className="text-2xl font-bold text-white">身份验证</h3>
                  <p className="text-gray-500 text-sm leading-relaxed">
                    为了维护社区秩序，我们需要关联您的 GitHub 账号以确认作者身份。
                  </p>
                </div>
                <button
                  type="button"
                  onClick={() => void signIn('github', '/upload')}
                  className="inline-flex items-center gap-3 bg-white text-black px-10 py-4 rounded-2xl font-bold hover:scale-105 active:scale-95 transition-all shadow-xl shadow-white/5"
                >
                  使用 GitHub 账号登录
                </button>
                <p className="text-[10px] text-gray-600 uppercase tracking-widest font-bold">
                  Secure Authorization via GitHub OAuth
                </p>
              </div>
            ) : null}

            {loggedIn && step === 1 ? (
              <div className="space-y-8">
                <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
                  <label className="group border-2 border-dashed border-white/10 p-8 rounded-3xl flex flex-col items-center cursor-pointer hover:border-[#40B5AD]/40 hover:bg-[#40B5AD]/5 transition-all text-center">
                    <span className="text-3xl transition-transform group-hover:scale-110">🖼️</span>
                    <div className="mt-3">
                      <p className={`text-sm font-bold truncate max-w-[200px] ${previewFile ? 'text-[#40B5AD]' : 'text-gray-400'}`}>
                        {previewFile ? previewFile.name : '选择预览图'}
                      </p>
                    </div>
                    <input
                      type="file"
                      onChange={(e: ChangeEvent<HTMLInputElement>) => setPreviewFile(e.target.files?.[0] ?? null)}
                      className="hidden"
                      accept="image/*"
                    />
                  </label>
                  <label className="group border-2 border-dashed border-white/10 p-8 rounded-3xl flex flex-col items-center cursor-pointer hover:border-[#40B5AD]/40 hover:bg-[#40B5AD]/5 transition-all text-center">
                    <span className="text-3xl transition-transform group-hover:scale-110">📦</span>
                    <div className="mt-3">
                      <p className={`text-sm font-bold truncate max-w-[200px] ${litematicFile ? 'text-[#40B5AD]' : 'text-gray-400'}`}>
                        {litematicFile ? litematicFile.name : '选择存档文件'}
                      </p>
                    </div>
                    <input
                      type="file"
                      onChange={(e: ChangeEvent<HTMLInputElement>) => setLitematicFile(e.target.files?.[0] ?? null)}
                      className="hidden"
                      accept=".litematic,.zip"
                    />
                  </label>
                </div>

                <div className="space-y-4">
                  <div className="grid grid-cols-2 gap-4">
                    <input
                      value={name}
                      onChange={(e) => setName(e.target.value)}
                      placeholder="作品名称"
                      className="bg-black/40 border border-white/10 p-4 rounded-xl text-white focus:border-[#40B5AD] outline-none transition-all"
                    />
                    <input
                      value={author}
                      onChange={(e) => setAuthor(e.target.value)}
                      placeholder="你的名称"
                      className="bg-black/40 border border-white/10 p-4 rounded-xl text-white focus:border-[#40B5AD] outline-none transition-all"
                    />
                  </div>
                  <input
                    value={contact}
                    onChange={(e) => setContact(e.target.value)}
                    placeholder="联系方式"
                    className="w-full bg-black/40 border border-white/10 p-4 rounded-xl text-white focus:border-[#40B5AD] outline-none transition-all"
                  />

                  <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                    <div className="flex flex-col space-y-2">
                      <span className="text-[10px] text-gray-500 font-bold uppercase px-1">编辑简介 (Markdown)</span>
                      <textarea
                        value={desc}
                        onChange={(e) => setDesc(e.target.value)}
                        className="w-full bg-black/40 border border-white/10 p-4 rounded-xl text-white h-64 focus:border-[#40B5AD] outline-none resize-none font-mono text-sm"
                      />
                    </div>
                    <div className="flex flex-col space-y-2">
                      <span className="text-[10px] text-[#40B5AD] font-bold uppercase px-1">实时渲染预览</span>
                      <div
                        className="w-full bg-white/[0.02] border border-white/5 p-4 rounded-xl text-gray-400 h-64 overflow-y-auto markdown-body text-sm"
                        dangerouslySetInnerHTML={{ __html: previewHtml }}
                      />
                    </div>
                  </div>
                </div>

                <div className="space-y-6 pt-4 border-t border-white/5">
                  <p className="text-[13px] text-gray-500 font-bold uppercase tracking-[0.2em]">分类标签</p>

                  <div className="space-y-3">
                    <div className="bg-white/[0.03] p-6 rounded-[2rem]">
                      {processedConfig.map((item) => (
                        <div key={item.mainCat} className="border-l-2 border-[#40B5AD]/20 pl-4 pt-5 mb-8 last:mb-0">
                          <h3 className="text-sm font-medium text-[#40B5AD] mb-6 flex items-center gap-2">
                            <span className="w-1.5 h-1.5 rounded-full bg-[#40B5AD]" />
                            {item.mainCat}
                          </h3>

                          {item.flattened.length > 0 ? (
                            <div className="flex flex-wrap gap-2 mb-6">
                              {item.flattened.map((tag) => (
                                <button
                                  key={tag}
                                  type="button"
                                  onClick={() => toggleTag(tag)}
                                  className={`px-3 py-1.5 rounded-lg text-[11px] transition-all border ${
                                    tags.includes(tag)
                                      ? 'bg-[#40B5AD] text-black border-[#40B5AD]'
                                      : 'bg-white/5 text-white/40 border-white/10 hover:border-white/30'
                                  }`}
                                >
                                  {tag}
                                </button>
                              ))}
                            </div>
                          ) : null}

                          {item.nested.map((sub) => (
                            <div key={sub.subCat} className="mb-8 last:mb-0">
                              <div className="flex mb-4">
                                <button
                                  type="button"
                                  onClick={() => toggleTag(sub.subCat)}
                                  className={`px-0 py-0.5 border-b-2 text-[12px] transition-all tracking-wider ${
                                    tags.includes(sub.subCat)
                                      ? 'text-[#40B5AD] border-[#40B5AD]'
                                      : 'text-white/40 border-white/10 hover:text-white/60'
                                  }`}
                                >
                                  {sub.subCat}
                                </button>
                              </div>
                              <div className="flex flex-wrap gap-2">
                                {sub.tags.map((tag) => (
                                  <button
                                    key={tag}
                                    type="button"
                                    onClick={() => toggleTag(tag, sub.subCat)}
                                    className={`px-3 py-1.5 rounded-lg text-[11px] transition-all border ${
                                      tags.includes(tag)
                                        ? 'bg-[#40B5AD] text-black border-[#40B5AD]'
                                        : 'bg-white/5 text-white/40 border-white/10 hover:border-white/30'
                                    }`}
                                  >
                                    {tag}
                                  </button>
                                ))}
                              </div>
                            </div>
                          ))}
                        </div>
                      ))}
                    </div>
                  </div>

                  <button
                    type="button"
                    onClick={() => void handleUpload()}
                    disabled={!isReady}
                    className="w-full bg-[#40B5AD] text-black py-5 rounded-2xl font-bold text-lg shadow-xl shadow-[#40B5AD]/20 hover:brightness-110 active:scale-[0.98] transition-all disabled:opacity-20 disabled:grayscale"
                  >
                    确认并提交投稿
                  </button>
                </div>
              </div>
            ) : null}

            {step === 2 ? (
              <div className="py-24 text-center space-y-6">
                <div className="text-5xl animate-bounce">🚀</div>
                <h3 className="text-2xl font-bold text-white tracking-widest">上传中</h3>
                <p className="text-gray-500">正在上传至服务器</p>
              </div>
            ) : null}

            {step === 3 ? (
              <div className="py-12 text-center space-y-8">
                <div className="text-6xl">🎉</div>
                <h3 className="text-2xl font-bold text-white">投递成功！</h3>
                <div className="max-w-sm mx-auto p-6 bg-white/5 rounded-2xl border border-white/10">
                  <p className="text-sm text-gray-400 leading-relaxed">
                    作品已登记。我们将在1-2周内尽量完成审核！如果超过我们深感抱歉！。
                  </p>
                </div>
                <a
                  href={githubIssueUrl}
                  target="_blank"
                  rel="noreferrer"
                  className="inline-block bg-[#40B5AD] text-black px-8 py-4 rounded-2xl font-bold shadow-lg hover:scale-105 transition-all"
                >
                  查看审核 Issue
                </a>
                <br />
                <button
                  type="button"
                  onClick={() => setStep(1)}
                  className="text-gray-500 text-xs hover:text-white transition-all underline"
                >
                  投递下一个项目
                </button>
              </div>
            ) : null}
          </div>
        </div>
      </div>
    </div>
  );
}
